def normalize(text) -> str:
    t = unicodedata.normalize("NFKC", str(text)).lower()
    t = re.sub(r"[*_\\`]", "", t)
    t = t.replace("|", " ")
    t = unicodedata.normalize("NFKC", t)
    return re.sub(r"\s+", " ", t).strip()


class CheckError(Exception):
    pass


def require(cond, msg):
    if not cond:
        raise CheckError(msg)


def required_strings(checks):
    out = list(checks["must_contain"]) + list(checks["ordered"]) + list(checks["headings"])
    for t in checks["tables"]:
        out += [c for row in t["rows"] for c in row if normalize(c)]
    return out


def verify_checks(name, gt, reading_text, *, headings_found=None, tables_found=None, also_in=()):
    """Verifies a ground truth against text read back from the generated file.

    reading_text: the document's text in human reading order, without page furniture.
    also_in: extra (label, text) pairs that must also contain must_contain/ordered/headings
    (for the PDF: the naive line-joined text, so no check depends on de-hyphenation).
    """
    c = gt["checks"]
    norm = normalize(reading_text)
    for p in c["must_contain"]:
        require(normalize(p) in norm, f"{name}: must_contain not found: {p!r}")
    require(not c["ordered"] or 4 <= len(c["ordered"]) <= 8, f"{name}: ordered must hold 4-8 anchors")
    positions = []
    for a in c["ordered"]:
        na = normalize(a)
        require(norm.count(na) == 1, f"{name}: ordered anchor {a!r} occurs {norm.count(na)} times (must be 1)")
        positions.append(norm.index(na))
        for b in c["ordered"]:
            require(a == b or na not in normalize(b), f"{name}: anchor {a!r} occurs inside anchor {b!r}")
    require(positions == sorted(positions), f"{name}: ordered anchors are not in reading order")
    for h in c["headings"]:
        require(normalize(h) in norm, f"{name}: heading not in text: {h!r}")
    if headings_found is not None:
        require(list(headings_found) == list(c["headings"]),
                f"{name}: headings read back {headings_found!r} != ground truth {c['headings']!r}")
    for t in c["tables"]:
        for row in t["rows"]:
            for cell in row:
                require(normalize(cell) in norm, f"{name}: table cell not in text: {cell!r}")
    if tables_found is not None:
        require([t["rows"] for t in c["tables"]] == tables_found, f"{name}: tables read back differ from ground truth")
    req = required_strings(c)
    for a in c["absent"]:
        require(normalize(a) not in norm, f"{name}: absent string {a!r} occurs in the reading text")
        for s in req:
            require(normalize(a) not in normalize(s), f"{name}: absent {a!r} occurs inside required text {s!r}")
    for n in c["noise"]:
        require(normalize(n["text"]) not in norm, f"{name}: noise text {n['text']!r} occurs in the body text")
        require(isinstance(n["max"], int) and n["max"] >= 0, f"{name}: bad noise max")
    for label, text in also_in:
        other = normalize(text)
        for p in list(c["must_contain"]) + list(c["ordered"]) + list(c["headings"]):
            require(normalize(p) in other, f"{name}: {p!r} not found in {label}")


MIN_PHRASE_WORDS = 6


def all_check_strings(checks):
    out = list(checks["must_contain"]) + list(checks["ordered"]) + list(checks["headings"]) + list(checks["absent"])
    out += [n["text"] for n in checks["noise"]]
    for t in checks["tables"]:
        out += [c for row in t["rows"] for c in row if normalize(c)]
    return out


def audit_policy(name, fmt, gt, reading_text, *, fields=None):
    """Audit rules (2026-11-24) on top of verify_checks.

    - No check string and no table name contains the corpus file name or its stem, and no check string can be
      satisfied by the lines a converter writes itself ('# <file name>', 'Source file:', 'Source type:', 'Source:').
    - Prose formats (fields=None): every must_contain phrase has at least MIN_PHRASE_WORDS words and occurs exactly
      once in the reading text (distinctive).
    - Data formats (fields = every key, value or cell as displayed): every must_contain item and ordered anchor is
      one complete field, and never occurs inside a different field.
    """
    c = gt["checks"]
    stem = Path(name).stem
    added = normalize(f"# {name}\nSource file: {name}\nSource type: {fmt}\nSource: {name}")
    for s in all_check_strings(c) + [t["name"] for t in c["tables"]]:
        ns = normalize(s)
        require(normalize(stem) not in ns, f"{name}: check text {s!r} contains the file name")
    for s in all_check_strings(c):
        require(normalize(s) not in added, f"{name}: check text {s!r} occurs in converter-added lines")
    norm = normalize(reading_text)
    if fields is None:
        for p in c["must_contain"]:
            require(len(p.split()) >= MIN_PHRASE_WORDS, f"{name}: must_contain {p!r} has fewer than "
                                                         f"{MIN_PHRASE_WORDS} words")
            require(norm.count(normalize(p)) == 1, f"{name}: must_contain {p!r} occurs {norm.count(normalize(p))} "
                                                   "times in the reading text (must be 1)")
    else:
        nf = [normalize(f) for f in fields]
        for p in list(c["must_contain"]) + list(c["ordered"]):
            n = normalize(p)
            require(n in nf, f"{name}: {p!r} is not one complete field")
            inside = sorted({f for f in nf if n in f and f != n})
            require(not inside, f"{name}: {p!r} also occurs inside other fields {inside[:3]}")


