def xlsx_display(value, number_format) -> str:
    """Cell text as Excel shows it, for the number formats this workbook uses."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if number_format == FMT_DATE and isinstance(value, (dt.date, dt.datetime)):
        return value.strftime("%Y-%m-%d")
    if number_format == FMT_INT and isinstance(value, int):
        return f"{value:,}"
    if number_format == FMT_USD:
        return f"${Decimal(repr(value)).quantize(Decimal('0.01'), rounding=ROUND_HALF_UP):,.2f}"
    if number_format == FMT_PCT:
        scaled = Decimal(repr(value)) * 100
        frac = abs(scaled * 10 - (scaled * 10).to_integral_value(rounding="ROUND_FLOOR"))
        require(abs(frac - Decimal("0.5")) > Decimal("1e-6"), "xlsx: percent value on a rounding boundary")
        return f"{scaled.quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)}%"
    raise ValueError(f"unexpected cell {value!r} with format {number_format!r}")


def xlsx_model():
    """Returns the cell grids (value, number_format) of both sheets, from the order data."""
    sales = [[(h or None, "General") for h in SALES_HEADER]]
    total_units, total_rev = 0, Decimal("0")
    per_region = {r: [0, 0, Decimal("0")] for r, _ in XLSX_REGION_MANAGERS}
    for no, day, customer, product, units in XLSX_ORDERS:
        price = XLSX_PRODUCTS[product]
        revenue = money(price * units)
        region = XLSX_CUSTOMER_REGION[customer]
        sales.append([(f"SO-26-{no:04d}", "General"), (day, FMT_DATE), (customer, "General"), (region, "General"),
                      (None, "General"), (product, "General"), (units, FMT_INT), (float(price), FMT_USD),
                      (float(revenue), FMT_USD)])
        total_units += units
        total_rev += revenue
        agg = per_region[region]
        agg[0] += 1
        agg[1] += units
        agg[2] += revenue
    sales.append([("Total", "General")] + [(None, "General")] * 5 + [(total_units, FMT_INT), (None, "General"),
                                                                    (float(total_rev), FMT_USD)])
    regions = [[(h, "General") for h in REGION_HEADER]]
    for region, manager in XLSX_REGION_MANAGERS:
        orders, units, revenue = per_region[region]
        regions.append([(region, "General"), (manager, "General"), (orders, FMT_INT), (units, FMT_INT),
                        (float(revenue), FMT_USD), (float(revenue / total_rev), FMT_PCT)])
