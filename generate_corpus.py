class Line:
    __slots__ = ("text", "justify", "hyphen")

    def __init__(self, text, justify, hyphen=None):
        self.text, self.justify, self.hyphen = text, justify, hyphen  # hyphen: (prefix, rest of word) or None


def break_lines(text, font, size, width, justify):
    """Greedy line breaking; a word that does not fit is split at a '~' point when its prefix + '-' fits."""
    def fits(s):
        return stringWidth(s, font, size) <= width + 1e-6

    tokens = text.split()
    lines, cur = [], []
    while tokens:
        tok = tokens.pop(0)
        word = tok.replace("~", "")
        if fits(" ".join(cur + [word])):
            cur.append(word)
            continue
        parts = tok.split("~")
        for k in range(len(parts) - 1, 0, -1):
            prefix = "".join(parts[:k])
            if fits(" ".join(cur + [prefix + "-"])):
                lines.append(Line(" ".join(cur + [prefix + "-"]), justify, (prefix, "".join(parts[k:]))))
                cur = []
                tokens.insert(0, "~".join(parts[k:]))
                break
        else:
            if not cur:
                raise ValueError(f"word too wide for the column: {word!r}")
            lines.append(Line(" ".join(cur), justify))
            cur = []
            tokens.insert(0, tok)
    if cur:
        lines.append(Line(" ".join(cur), False))
    return lines


class Lines(Flowable):
    """A paragraph whose lines are broken in advance; drawn line by line, justified with word spacing (Tw)."""

    def __init__(self, lines, font, size, leading, width, kind, *, space_before=0.0, space_after=0.0,
                 para_id=None, continued=False):
        super().__init__()
        self.lines, self.font, self.size, self.leading, self.width = lines, font, size, leading, width
        self.kind, self.para_id, self.continued = kind, para_id, continued
        self.spaceBefore, self.spaceAfter = space_before, space_after
        self.height = len(lines) * leading

    def wrap(self, availWidth, availHeight):
        if abs(availWidth - self.width) > 0.01:
            raise ValueError(f"frame width {availWidth} != prepared width {self.width}")
        return self.width, self.height

    def split(self, availWidth, availHeight):
        n = int((availHeight + 1e-6) // self.leading)
        total = len(self.lines)
        if n >= total:
            return [self]
        n = min(n, total - 2)  # no widow: at least two lines go to the next column
        while n > 0 and self.lines[n - 1].hyphen:  # never break a column or page inside a hyphenated word
            n -= 1
        if n < 2:  # no orphan: at least two lines stay
            return []
        common = dict(para_id=self.para_id)
        return [Lines(self.lines[:n], self.font, self.size, self.leading, self.width, self.kind,
                      space_before=self.spaceBefore, continued=self.continued, **common),
                Lines(self.lines[n:], self.font, self.size, self.leading, self.width, self.kind,
                      space_after=self.spaceAfter, continued=True, **common)]

    def draw(self):
        c = self.canv
        for i, line in enumerate(self.lines):
            c.saveState()
            t = c.beginText(0, self.height - i * self.leading - 0.82 * self.size)
            t.setFont(self.font, self.size)
            spaces = line.text.count(" ")
            extra = 0.0
            if line.justify and spaces:
                extra = (self.width - stringWidth(line.text, self.font, self.size)) / spaces
            t.setWordSpace(extra)
            t.textOut(line.text)
            c.drawText(t)
            c.restoreState()


class NeedSpace(Flowable):
    """Moves to the next frame unless `needed` points are left (keeps headings with text, tables whole)."""

    def __init__(self, needed):
        super().__init__()
        self.needed = needed

    def wrap(self, availWidth, availHeight):
        return availWidth, (0 if availHeight + 1e-6 >= self.needed else availHeight + 1)

    def split(self, availWidth, availHeight):
        return []

    def draw(self):
        pass


class PaperDoc(BaseDocTemplate):
    def __init__(self, filename, title_height):
        super().__init__(filename, pagesize=letter, leftMargin=MARGIN_X, rightMargin=MARGIN_X,
                         topMargin=MARGIN_TOP, bottomMargin=MARGIN_BOTTOM, invariant=1, title=PDF_TITLE,
                         author="Operations Engineering Group",
                         subject="Sorting automation options for the 2027 capital budget",
                         creator="generate_corpus.py")
        self.records = []
        self.title_height = title_height
        top = PAGE_H - MARGIN_TOP
        col_h_first = top - title_height - 12 - MARGIN_BOTTOM
        col_h = top - MARGIN_BOTTOM
        right_x = MARGIN_X + COL_W + GUTTER
        pad = dict(leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0)
        first = PageTemplate(id="first", onPage=self.furniture, frames=[
            Frame(MARGIN_X, top - title_height, FULL_W, title_height, id="title", **pad),
            Frame(MARGIN_X, MARGIN_BOTTOM, COL_W, col_h_first, id="left", **pad),
            Frame(right_x, MARGIN_BOTTOM, COL_W, col_h_first, id="right", **pad)])
        later = PageTemplate(id="later", onPage=self.furniture, frames=[
            Frame(MARGIN_X, MARGIN_BOTTOM, COL_W, col_h, id="left", **pad),
            Frame(right_x, MARGIN_BOTTOM, COL_W, col_h, id="right", **pad)])
        self.addPageTemplates([first, later])

    def furniture(self, canv, doc):
        canv.setDateFormatter(lambda *_: PDF_DATE)  # fixed CreationDate/ModDate instead of invariant 2000-01-01
        canv.saveState()
        canv.setFont("Helvetica", 8)
        canv.drawString(MARGIN_X, PAGE_H - 46, PDF_HEADER_LEFT)
        canv.drawRightString(PAGE_W - MARGIN_X, PAGE_H - 46, PDF_HEADER_RIGHT)
        canv.setLineWidth(0.5)
        canv.line(MARGIN_X, PAGE_H - 51, PAGE_W - MARGIN_X, PAGE_H - 51)
        canv.drawCentredString(PAGE_W / 2, 42, f"{PDF_FOOTER} - Page {doc.page} of {PDF_TOTAL_PAGES}")
        if doc.page == 1:
            y = PAGE_H - MARGIN_TOP - self.title_height - 6
            canv.line(MARGIN_X, y, PAGE_W - MARGIN_X, y)
        canv.restoreState()

    def afterFlowable(self, flowable):
        if isinstance(flowable, (Lines, Table)):
            self.records.append((self.page, self.frame.id, flowable))


def pdf_story():
    """Returns (title_height, story, list of body Lines in content order)."""
    title = Lines(break_lines(PDF_TITLE, "Helvetica-Bold", 20, FULL_W, False), "Helvetica-Bold", 20, 24, FULL_W,
                  "title", para_id="title")
    byline = Lines(break_lines(PDF_BYLINE, "Helvetica", 10, FULL_W, False), "Helvetica", 10, 13, FULL_W, "byline",
                   space_before=4, para_id="byline")
    summary = Lines(break_lines(PDF_SUMMARY, "Times-Italic", 10.5, FULL_W, True), "Times-Italic", 10.5, 13.5,
                    FULL_W, "summary", space_before=10, para_id="summary")
    title_height = title.height + 4 + byline.height + 10 + summary.height + 2
    story = [title, byline, summary, NextPageTemplate("later"), FrameBreak()]
    for s_index, (heading, paragraphs) in enumerate(PDF_SECTIONS):
        h = Lines(break_lines(heading, FONT_HEAD, SIZE_HEAD, COL_W, False), FONT_HEAD, SIZE_HEAD, LEAD_HEAD, COL_W,
                  "heading", space_before=9, space_after=3, para_id=f"h{s_index}")
        story += [NeedSpace(9 + h.height + 3 + 2 * LEAD_BODY), h]
        for p_index, text in enumerate(paragraphs):
            if text == "@TABLE":
                cap = Lines(break_lines(PDF_TABLE_CAPTION, FONT_CAP, SIZE_CAP, COL_W, False), FONT_CAP, SIZE_CAP,
                            LEAD_CAP, COL_W, "caption", space_before=4, space_after=3, para_id="caption")
                widths = [max(stringWidth(row[c], "Helvetica-Bold" if r == 0 else "Helvetica", 8)
                              for r, row in enumerate(PDF_TABLE)) + 6 for c in range(len(PDF_TABLE[0]))]
                require(sum(widths) <= COL_W, "pdf: table wider than the column")
                widths[0] += COL_W - sum(widths)
                table = Table(PDF_TABLE, colWidths=widths, hAlign="LEFT")
                table.setStyle(TableStyle([
                    ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8),
                    ("FONT", (0, 1), (-1, -1), "Helvetica", 8),
                    ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
                    ("LINEABOVE", (0, 0), (-1, 0), 0.8, colors.black),
                    ("LINEBELOW", (0, 0), (-1, 0), 0.5, colors.black),
                    ("LINEBELOW", (0, -1), (-1, -1), 0.8, colors.black),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                    ("LEFTPADDING", (0, 0), (-1, -1), 3),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 3),
                ]))
                table.spaceBefore, table.spaceAfter = 0, 8
                _, table_h = table.wrap(COL_W, PAGE_H)
                story += [NeedSpace(4 + cap.height + 3 + table_h), cap, table]
                continue
            story.append(Lines(break_lines(text, FONT_BODY, SIZE_BODY, COL_W, True), FONT_BODY, SIZE_BODY, LEAD_BODY,
                               COL_W, "body", space_after=5, para_id=f"p{s_index}.{p_index}"))
    return title_height, story


def lines_text(lines, dehyphenate):
    out = ""
    for line in lines:
        if dehyphenate and line.hyphen:
            out += line.text[:-1]
        else:
            out += line.text + " "
    return out.strip()


def build_pdf(path: Path):
    title_height, story = pdf_story()
    doc = PaperDoc(str(path), title_height)
    doc.build(story)
    require(doc.page == PDF_TOTAL_PAGES, f"pdf: layout produced {doc.page} pages, expected {PDF_TOTAL_PAGES}")
    return doc.records


def make_pdf():
    path = CORPUS / "gen-two-column.pdf"
    records = build_pdf(path)

    # Segments in reading order: page by page; title block, then left column, then right column.
    segments = []  # [(page, frame, reading_text, naive_text, [records])]
    for page, frame, flowable in records:
        if not segments or segments[-1][0] != (page, frame):
            segments.append([(page, frame), [], [], []])
        seg = segments[-1]
        seg[3].append(flowable)
        if isinstance(flowable, Lines):
            seg[1].append(lines_text(flowable.lines, True))
            seg[2].append(lines_text(flowable.lines, False))
        else:
            seg[1] += [" ".join(row) for row in flowable._cellvalues]
            seg[2] += [" ".join(row) for row in flowable._cellvalues]
    order = [s[0] for s in segments]
    expected_order = [(1, "title"), (1, "left"), (1, "right")] + [(p, f) for p in range(2, PDF_TOTAL_PAGES + 1)
                                                                  for f in ("left", "right")]
    require(order == expected_order, f"pdf: frames used {order}, expected every column of every page")
    reading = "\n".join("\n".join(s[1]) for s in segments)
    naive = "\n".join("\n".join(s[2]) for s in segments)

    hyphenated = []  # (page, frame, prefix, rest)
    for (page, frame), _, _, flows in segments:
        for f in flows:
            if isinstance(f, Lines):
                hyphenated += [(page, frame) + ln.hyphen for ln in f.lines if ln.hyphen]
    require(len(hyphenated) >= 3, f"pdf: only {len(hyphenated)} hyphenated line ends")
    absent = []
    for _, _, prefix, rest in hyphenated:
        tail = re.match(r"[A-Za-z]+", rest).group(0)
        for form in (f"{prefix}- {tail}", f"{prefix}-{tail}"):
            if form not in absent:
                absent.append(form)
    for form in absent[::2]:
        require(normalize(form) in normalize(naive), f"pdf: split form {form!r} not in the drawn lines")

    # Ordered anchors: the title, then the start of the first paragraph that begins in each column.
    anchors = [PDF_TITLE]
    norm_reading = normalize(reading)
    for (page, frame), _, _, flows in segments:
        if frame == "title":
            continue
        starts = [f for f in flows if isinstance(f, Lines) and f.kind == "body" and not f.continued]
        require(starts, f"pdf: no paragraph starts in page {page} {frame} column")
        first_line = starts[0].lines[0]
        words = first_line.text.split()
        if first_line.hyphen:
            words = words[:-1]
        for n in range(6, len(words) + 1):
            anchor = " ".join(words[:n]).rstrip(",.;:")
            if norm_reading.count(normalize(anchor)) == 1:
                break
        else:
            raise CheckError(f"pdf: no unique anchor on page {page} {frame}")
        anchors.append(anchor)

    table_rec = [(p, f) for p, f, fl in records if isinstance(fl, Table)]
    require(len(table_rec) == 1, "pdf: the table was split or drawn more than once")
    words_list = ", ".join(sorted({p + re.match(r"[A-Za-z]+", r).group(0) for _, _, p, r in hyphenated},
                                  key=str.lower))
    # Absent entries: each hyphenated word is one word without a real hyphen in the source text, and neither
    # artifact form occurs anywhere a reader sees text (body, title block, table, running header and footer).
    source_tokens = {t.replace("~", "").strip(",.;:()").lower(): t for _, paras in PDF_SECTIONS for para in paras
                     for t in para.split() if "~" in t}
    furniture = [PDF_HEADER_LEFT, PDF_HEADER_RIGHT] + [f"{PDF_FOOTER} - Page {n} of {PDF_TOTAL_PAGES}"
                                                       for n in range(1, PDF_TOTAL_PAGES + 1)]
    visible = normalize(reading + "\n" + "\n".join(furniture))
    for _, _, prefix, rest in hyphenated:
        word = (prefix + re.match(r"[A-Za-z]+", rest).group(0)).lower()
        require(word in source_tokens and "-" not in source_tokens[word],
                f"pdf: hyphenated {word!r} is not a single unhyphenated source word")
        require(re.search(rf"\b{word}\b", normalize(reading)), f"pdf: joined word {word!r} not in the reading text")
    for form in absent:
        require(normalize(form) not in visible, f"pdf: absent {form!r} occurs in visible text")
    checks = {
        "must_contain": PDF_MUST,
        "ordered": anchors,
        "headings": [PDF_TITLE] + [h for h, _ in PDF_SECTIONS],
        "tables": [{"name": PDF_TABLE_CAPTION, "rows": PDF_TABLE}],
        "noise": [{"text": PDF_HEADER_LEFT, "max": 1}, {"text": PDF_HEADER_RIGHT, "max": 1},
                  {"text": PDF_FOOTER, "max": 1}],
        "absent": absent,
    }
    split_desc = "; ".join(f"p{pg} {fr}: {p}-/{r}" for pg, fr, p, r in hyphenated)
    gt = write_ground_truth(
        path, fmt="pdf", title=PDF_TITLE, pages_or_sheets=PDF_TOTAL_PAGES,
        stresses=["two-column reading order (left column, then right column, page by page)",
                  "full-width title block and summary above the columns on page 1",
                  "running header and page-number footer on every page",
                  "numbered section headings",
                  "simple ruled table inside a column",
                  "words hyphenated at line ends",
                  "justified text (word spacing set with the PDF Tw operator)"],
        checks=checks,
        notes=(f"US Letter, 3 pages, standard Type 1 fonts (Times, Helvetica; not embedded), text drawn line by line. "
               f"Page 1 starts with a full-width title, byline and italic summary; all body text is in two "
               f"columns. Every page has the running header '{PDF_HEADER_LEFT}' (left) and '{PDF_HEADER_RIGHT}' "
               f"(right) and the footer '{PDF_FOOTER} - Page N of 3'; each constant string may appear at most once. "
               f"All three noise entries are visible page furniture; the file has no invisible text-layer stamps. "
               f"ordered = the title, then the opening words of the first paragraph that starts in each column "
               f"(page 1 left, page 1 right, ..., page 3 right), taken from the generator's layout log; all are "
               f"body text and the file has no footnotes. headings are the title (20 pt Helvetica-Bold, the "
               f"largest text on page 1) and the {len(PDF_SECTIONS)} numbered section headings (11 pt "
               f"Helvetica-Bold, body text is Times-Roman); the italic table caption and the italic 'Summary.' "
               f"paragraph are not headings. Words hyphenated at line ends ({len(hyphenated)}): {split_desc}. "
               f"absent lists, for each, the line-break form 'prefix- rest' and the joined-with-hyphen form "
               f"'prefix-rest'; a correct conversion writes the whole word ({words_list}). Each of these is one "
               f"word with no hyphen of its own (every one is also printed unbroken elsewhere or is an ordinary "
               f"dictionary word), and neither artifact form occurs anywhere in the visible text, header or "
               f"footer. No must_contain phrase or anchor spans a hyphenated word or a column break, so text "
               f"recall and order do not depend on de-hyphenation. Table 1 is on page {table_rec[0][0]}, "
               f"{table_rec[0][1]} column. Real hyphens in compounds (cross-belt, next-day, go-live, "
               f"post-implementation) are never line-break points. The document information dictionary repeats "
               f"the title and the author 'Operations Engineering Group'; must_contain uses the full printed "
               f"byline, which that metadata cannot satisfy."),
        audit=("Replaced must_contain 'Operations Engineering Group' (3 words, and also the PDF Author metadata) "
               "with the full printed byline 'Operations Engineering Group, Fernhill Logistics. November 2026.'. "
               "Added the title to headings: it is styled as a heading (20 pt bold, largest text), PDFs have no "
               "style names, and the public PDFs of this corpus list their titles as headings too. Kept noise "
               "(visible running header and footer, max 1 each) and the 20 absent strings after re-checking "
               "every hyphenated word against the source text and the rendered pages. Ordered anchors and the "
               "table re-checked against the rendered pages: unchanged."))
    verify_checks(path.name, gt, reading, also_in=[("the naive line-joined text", naive)])
    audit_policy(path.name, "pdf", gt, reading)
    for p in PDF_MUST + anchors:
        require(any(normalize(p) in normalize("\n".join(s[2])) for s in segments),
                f"pdf: {p!r} spans a column or page break")

    tool = shutil.which("pdftotext")
    if tool:
        out = subprocess.run([tool, "-raw", "-enc", "UTF-8", str(path), "-"], stdin=subprocess.DEVNULL,
                             capture_output=True, check=True).stdout.decode("utf-8")
        ext = normalize(out)
        for p in PDF_MUST + checks["headings"] + [c for row in PDF_TABLE for c in row]:
            require(normalize(p) in ext, f"pdf (pdftotext): {p!r} not extracted")
        pos = [ext.find(normalize(a)) for a in anchors]
        require(all(x >= 0 for x in pos) and pos == sorted(pos), "pdf (pdftotext): anchors out of order")
        for n in checks["noise"]:
            require(ext.count(normalize(n["text"])) == PDF_TOTAL_PAGES, f"pdf (pdftotext): {n['text']!r} count")
        print(f"  pdftotext -raw cross-check passed ({tool})")
    else:
        print("  pdftotext not on PATH: external PDF cross-check skipped")
    return gt


