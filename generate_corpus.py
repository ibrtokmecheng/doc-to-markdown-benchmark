#!/usr/bin/env python3
"""Generate the synthetic ("generated") part of the doc-to-markdown benchmark corpus.

Writes six documents to corpus/ and one ground-truth JSON per document to
corpus/ground-truth/<file>.json (schema: see the benchmark README / score.mjs):

    gen-report.docx         gen-sales.xlsx          gen-deck.pptx
    gen-orders.csv          gen-api-response.json   gen-two-column.pdf

Everything is fixed in this file: content, dates, layout. There is no randomness
and no clock input. Every ground-truth item is derived from the same Python data
that is written into the document (single source of truth); the PDF reading order,
hyphenated words and column anchors come from the generator's own layout log.

After writing, each file is read back (python-docx, openpyxl, python-pptx, csv,
json; for the PDF the layout log, plus `pdftotext -raw` when it is on PATH) and
every check is verified again, together with the audit rules of 2026-11-24
(audit_policy: no file name or converter-added text in any check; prose phrases
of at least 6 words that occur once; data-file items are whole, distinctive
fields). Any mismatch aborts with exit status 1.

Run from any folder that has no pyproject.toml above it (ephemeral environment,
no global installs):

    uv run --with python-docx --with openpyxl --with python-pptx --with reportlab \
        python3 generate_corpus.py

Only the twelve files named above are written; nothing else in corpus/ is touched.
Same library versions => byte-identical files: ZIP entry times and document
dates are pinned, and ReportLab runs in invariant mode. The library versions used
are recorded in each ground truth's "notes".
"""

