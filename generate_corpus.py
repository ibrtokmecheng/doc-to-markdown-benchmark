def _docx_add_numbering(document):
    """Adds one multilevel bullet list and one decimal list (as Word writes them: List Paragraph + numPr)."""
    numbering = document.part.numbering_part.element
    bullet = parse_xml(
        f'<w:abstractNum {nsdecls("w")} w:abstractNumId="{BULLET_NUM_ID}">'
        '<w:multiLevelType w:val="hybridMultilevel"/>'
        '<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="bullet"/><w:lvlText w:val="•"/>'
        '<w:lvlJc w:val="left"/><w:pPr><w:ind w:left="720" w:hanging="360"/></w:pPr></w:lvl>'
        '<w:lvl w:ilvl="1"><w:start w:val="1"/><w:numFmt w:val="bullet"/><w:lvlText w:val="o"/>'
        '<w:lvlJc w:val="left"/><w:pPr><w:ind w:left="1440" w:hanging="360"/></w:pPr>'
        '<w:rPr><w:rFonts w:ascii="Courier New" w:hAnsi="Courier New" w:hint="default"/></w:rPr></w:lvl>'
        '</w:abstractNum>')
    decimal = parse_xml(
        f'<w:abstractNum {nsdecls("w")} w:abstractNumId="{NUMBER_NUM_ID}">'
        '<w:multiLevelType w:val="hybridMultilevel"/>'
        '<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="decimal"/><w:lvlText w:val="%1."/>'
        '<w:lvlJc w:val="left"/><w:pPr><w:ind w:left="720" w:hanging="360"/></w:pPr></w:lvl>'
        '</w:abstractNum>')
    first_num = numbering.find(qn("w:num"))
    first_num.addprevious(bullet)
    first_num.addprevious(decimal)
    for num_id in (BULLET_NUM_ID, NUMBER_NUM_ID):
        numbering.append(parse_xml(
            f'<w:num {nsdecls("w")} w:numId="{num_id}"><w:abstractNumId w:val="{num_id}"/></w:num>'))


def _docx_list_item(document, text, level, num_id):
    p = document.add_paragraph(text, style="List Paragraph")
    num_pr = p._p.get_or_add_pPr().get_or_add_numPr()
    num_pr.get_or_add_ilvl().val = level
    num_pr.get_or_add_numId().val = num_id
    return p


def build_docx(path: Path):
    total = sum(Decimal(v) for row in DOCX_TABLE[2:] for v in row[1:])
    require(f"{total / 1000:.2f} million parcels" == "1.15 million parcels", "docx: table total != 1.15 million")

    document = docx.Document()
    style_names = {s.name for s in document.styles}
    for needed in ("Title", "Heading 1", "Heading 2", "List Paragraph", "Table Grid", "Caption"):
        require(needed in style_names, f"docx: template lacks style {needed!r}")
    _docx_add_numbering(document)

    for kind, payload in DOCX_BLOCKS:
        if kind == "title":
            document.add_paragraph(payload, style="Title")
        elif kind in ("h1", "h2"):
            document.add_heading(payload, level=1 if kind == "h1" else 2)
        elif kind == "para":
            p = document.add_paragraph()
            for text, fmt in payload:
                run = p.add_run(text)
                run.bold = fmt == "b" or None
                run.italic = fmt == "i" or None
        elif kind == "caption":
            document.add_paragraph(payload, style="Caption")
        elif kind == "bullet":
            _docx_list_item(document, payload[1], payload[0], BULLET_NUM_ID)
        elif kind == "number":
            _docx_list_item(document, payload[1], payload[0], NUMBER_NUM_ID)
        elif kind == "table":
            rows, cols = len(DOCX_TABLE), len(DOCX_TABLE[0])
            table = document.add_table(rows=rows, cols=cols)
            table.style = "Table Grid"
            r, c0, c1 = DOCX_MERGE
            table.cell(r, c0).merge(table.cell(r, c1))
            for ri, row in enumerate(DOCX_TABLE):
                if ri < 2:  # two header rows, repeated on each page
                    table.rows[ri]._tr.get_or_add_trPr().append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))
                for ci, value in enumerate(row):
                    if ri == r and c0 < ci <= c1:
                        continue  # covered by the merged cell
                    cell = table.cell(ri, ci)
                    cell.text = value
                    para = cell.paragraphs[0]
                    if ri < 2:
                        for run in para.runs:
                            run.bold = True
                        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    elif ci > 0:
                        para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        else:
            raise ValueError(kind)

    for para in document.paragraphs:
        if para.style.name == "Normal":
            para.paragraph_format.space_after = Pt(6)
    props = document.core_properties
    props.title = DOCX_TITLE
    props.subject = "Quarterly operations review"
    props.author = "Operations Analytics"
    props.last_modified_by = "Operations Analytics"
    props.comments = ""
    props.keywords = ""
