def read_docx(path: Path):
    """Body text in order (tables as grids with merged cells written once), headings, tables, list items,
    footnote texts and the page-header text, read back from the file."""
    document = docx.Document(path)
    texts, headings, tables, items = [], [], [], []
    for child in document.element.body.iterchildren():
        if child.tag == qn("w:p"):
            p = Paragraph(child, document)
            text = "".join(t.text or "" for t in child.iter(qn("w:t")))  # includes hyperlink runs
            texts.append(text)
            if p.style.name.startswith("Heading"):
                headings.append(text)
            num_pr = child.find(f"{qn('w:pPr')}/{qn('w:numPr')}")
            if num_pr is not None:
                items.append((int(num_pr.find(qn("w:numId")).get(qn("w:val"))),
                              int(num_pr.find(qn("w:ilvl")).get(qn("w:val"))), text))
        elif child.tag == qn("w:tbl"):
            grid = []
            for tr in child.iter(qn("w:tr")):
                row = []
                for tc in tr.iter(qn("w:tc")):
                    pr = tc.find(qn("w:tcPr"))
                    span = pr.find(qn("w:gridSpan")) if pr is not None else None
                    vmerge = pr.find(qn("w:vMerge")) if pr is not None else None
                    text = "\n".join("".join(t.text or "" for t in p.iter(qn("w:t"))) for p in tc.iter(qn("w:p")))
                    if vmerge is not None and vmerge.get(qn("w:val")) != "restart":
                        text = ""  # continuation of a vertically merged cell
                    n = int(span.get(qn("w:val"))) if span is not None else 1
                    row += [text] + [""] * (n - 1)
                grid.append(row)
            tables.append(grid)
            texts += [" ".join(row) for row in grid]
    fn_part = next(r.target_part for r in document.part.rels.values() if r.reltype == RT.FOOTNOTES)
    fn_root = parse_xml(fn_part.blob)
    footnotes = {}
    for fn in fn_root.iter(qn("w:footnote")):
        fid = int(fn.get(qn("w:id")))
        if fid > 0:
            footnotes[fid] = "".join(t.text or "" for t in fn.iter(qn("w:t"))).strip()
    refs = [int(r.get(qn("w:id"))) for r in document.element.body.iter(qn("w:footnoteReference"))]
    header = document.sections[0].header.paragraphs[0].text
    return "\n".join(texts), headings, tables, items, footnotes, refs, header


