def xlsx_display(value, fmt) -> str:
    """Cell text as Excel (en-US) shows it, for the number formats used here."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if fmt == FMT_DATE:
        return f"{value.day} {value.strftime('%b')} {value.year}"
    if fmt == "General" and isinstance(value, int):
        return str(value)
    d = Decimal(repr(value)) if isinstance(value, float) else Decimal(value)
    if fmt == FMT_GBP0:
        require(d == d.to_integral_value(), "xlsx: non-integer in a whole-pound cell")
        return f"(£{-d:,.0f})" if d < 0 else f"£{d:,.0f}"
    if fmt == FMT_GBP2:
        return f"£{money(d):,.2f}"
    if fmt in (FMT_PCT,):
        scaled = d * 100
        frac = abs(scaled * 10 - (scaled * 10).to_integral_value(rounding="ROUND_FLOOR"))
        require(abs(frac - Decimal("0.5")) > Decimal("1e-6"), "xlsx: percent on a rounding boundary")
        return f"{scaled.quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)}%"
    if fmt == FMT_INT:
        return f"{int(d):,}"
    if fmt == FMT_RATE:
        return f"{d.quantize(Decimal('0.0001'), rounding=ROUND_HALF_UP)}"
    if fmt == FMT_ONE:
        return f"{d.quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)}"
    raise ValueError(f"unexpected cell {value!r} with format {fmt!r}")


def xlsx_model():
    """Returns {sheet: rows of (value, number_format, formula or None)} and the formula cached values."""
    summary = [[(h, "General", None) for h in SUMMARY_HEADER]]
    r0 = SUMMARY_FIRST_ROW
    for k, (dept, budget, actual) in enumerate(BUDGET):
        r = r0 + 1 + k
        var = actual - budget
        summary.append([(dept, "General", None), (budget, FMT_GBP0, None), (actual, FMT_GBP0, None),
                        (var, FMT_GBP0, f"C{r}-B{r}"), (var / budget, FMT_PCT, f"D{r}/B{r}"),
                        (status_of(var, budget), "General", None)])
    last = r0 + len(BUDGET)
    tot_b = sum(b for _, b, _ in BUDGET)
    tot_a = sum(a for _, _, a in BUDGET)
    rt = last + 1
    summary.append([("Total", "General", None), (tot_b, FMT_GBP0, f"SUM(B{r0 + 1}:B{last})"),
                    (tot_a, FMT_GBP0, f"SUM(C{r0 + 1}:C{last})"), (tot_a - tot_b, FMT_GBP0, f"SUM(D{r0 + 1}:D{last})"),
                    ((tot_a - tot_b) / tot_b, FMT_PCT, f"D{rt}/B{rt}"),
                    (status_of(tot_a - tot_b, tot_b), "General", None)])
    inv = [[(h, "General", None) for h in INVOICE_HEADER]]
    for no, supplier, day, due, amount, status, overdue in invoices():
        inv.append([(no, "General", None), (supplier, "General", None), (day, FMT_DATE, None), (due, FMT_DATE, None),
                    (float(amount), FMT_GBP2, None), (status, "General", None),
                    (overdue, "General", None)])
    assumptions = [[("Parameter", "General", None), ("Value", "General", None), ("Notes", "General", None)]]
    for name, value, fmt, note in ASSUMPTIONS:
        assumptions.append([(name, "General", None), (value, fmt, None), (note, "General", None)])
    return {"Summary": summary, "Invoices": inv, "Assumptions": assumptions}


